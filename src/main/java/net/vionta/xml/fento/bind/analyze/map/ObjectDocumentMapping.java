package net.vionta.xml.fento.bind.analyze.map;

/**
 * Main class of the mapping element.
 */
public class ObjectDocumentMapping extends BaseMapping {

	@Override
	public String toString() {
		return "ObjectDocumentMapping [propertyName=" + propertyName + ", mappingExpression=" + mappingExpression
				+ ", propertyClass=" + propertyClass + ", propertyFormatter=" + propertyFormatter + ", \n   mappings="
				+ mappings + "]";
	}

	
}
